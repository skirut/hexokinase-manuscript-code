# ===================== USER SETTINGS =====================
from scripts.utils.paths import BOUND_DIR, LIGAND_INTERACTIONS_DIR

BOUND_DIR = BOUND_DIR
OUTROOT = LIGAND_INTERACTIONS_DIR / "com"

TOPO_NAME  = "structure.prmtop"
TRAJ_NAME  = "output.xtc"
STRIDE     = 1
LIG_PREFERRED = "G6P"
ROLL_WIN   = 50

MAX_WORKERS = min(20, os.cpu_count() or 4)

CGREEN  = "#009E73"
CPURPLE = "#CC79A7"

ENZYME_NAME = {"1qha": "HK1", "2nzt": "HK2", "3hm8": "HK3"}

SYSTEM_MAPPING = {
    '1qha': '1QHA_model_with_G6P',
    '1qha_G87E': '1QHA_G87E_G6P',
    '2nzt': '2nzt_model_with_G6P',
    '2nzt_D84Y': '2nzt_D84Y_G6P',
    '2nzt_D861Y': '2nzt_D861Y_G6P',
    '2nzt_T680M': '2nzt_T680M_G6P',
    '3hm8': '3hm8_model_with_G6P',
    '3hm8_D867N': '3hm8_D867N_G6P',
    '3hm8_D867Y': '3hm8_D867Y_G6P',
    '3hm8_T546M': '3hm8_T546M_G6P'
}
PH_LEVELS = ['3.0', '5.0', '7.0']

warnings.filterwarnings("ignore", category=UserWarning)
warnings.filterwarnings("ignore", category=DeprecationWarning)

# ========================================================

def ensure_outdirs():
    os.makedirs(OUTROOT, exist_ok=True)
    os.makedirs(os.path.join(OUTROOT, "per_system"), exist_ok=True)
    os.makedirs(os.path.join(OUTROOT, "master_grids"), exist_ok=True)

def list_bound_systems():
    systems = []
    for internal_name, bound_prefix in SYSTEM_MAPPING.items():
        parts = internal_name.split('_')
        base = parts[0].lower()
        mut = parts[1] if len(parts) > 1 else 'WT'
        
        for ph in PH_LEVELS:
            sysdir = os.path.join(BOUND_DIR, f"{bound_prefix}_pH{ph}", "prod")
            topo = os.path.join(sysdir, TOPO_NAME)
            traj = os.path.join(sysdir, TRAJ_NAME)

            if os.path.isfile(topo) and os.path.isfile(traj):
                systems.append((f"{base}_{mut}", float(ph), topo, traj))
    return systems

def smooth_series(vals, window=ROLL_WIN):
    if not len(vals): return vals
    return pd.Series(vals).rolling(window=max(3, min(window, len(vals))), min_periods=1).mean().to_numpy()

def analyze_one(args):
    rowkey, pH, topo, traj = args
    import MDAnalysis as mda
    
    out_dir = os.path.join(OUTROOT, "per_system", f"{rowkey}_pH{pH:g}")
    os.makedirs(out_dir, exist_ok=True)
    
    try:
        u = mda.Universe(topo, traj)
    except Exception as e:
        return {"ok": False, "rowkey": rowkey, "pH": pH, "msg": str(e)}

    # Ensure heavy atoms only for stable COM calculation
    lig_heavy = u.select_atoms(f"resname {LIG_PREFERRED} and not name H*")
    prot_heavy = u.select_atoms("protein and not name H*")
    
    if lig_heavy.n_atoms == 0 or prot_heavy.n_atoms == 0:
        return {"ok": False, "rowkey": rowkey, "pH": pH, "msg": "Empty selection for COM"}

    times_ns, com_nm = [], []
    
    for ts in u.trajectory[::STRIDE]:
        times_ns.append(float(getattr(ts, "time", ts.frame * (getattr(ts, "dt", 1.0) or 1.0))) / 1000.0)
        try:
            # Ligand vs Entire Protein
            dist = np.linalg.norm(prot_heavy.center_of_mass() - lig_heavy.center_of_mass()) / 10.0
            com_nm.append(dist)
        except Exception:
            com_nm.append(np.nan)

    t_ns = np.asarray(times_ns)
    com_arr = np.asarray(com_nm)
    
    com_csv = os.path.join(out_dir, "com_counts.csv")
    pd.DataFrame({
        "time_ns": t_ns, 
        "com_nm": com_arr, 
        "com_nm_ma": smooth_series(com_arr)
    }).to_csv(com_csv, index=False)

    return {"ok": True, "rowkey": rowkey, "pH": pH, "csv": com_csv}

def plot_publication_grid(df_prot, base):
    unique_phs = sorted(df_prot["pH"].unique())
    muts = df_prot["mut"].unique().tolist()
    if "WT" in muts:
        muts.remove("WT")
        mut_order = ["WT"] + sorted(muts)
    else: 
        mut_order = sorted(muts)

    n_muts, n_phs = len(mut_order), len(unique_phs)
    fig, axes = plt.subplots(n_muts, n_phs * 2, figsize=(3.5 * n_phs * 2, 3.2 * n_muts))
    axes = np.atleast_2d(axes)
    fig.subplots_adjust(left=0.08, right=0.98, top=0.82, bottom=0.12, wspace=0.35, hspace=0.65)

    letters = string.ascii_uppercase
    enz_name = ENZYME_NAME.get(base, base.upper())
    
    fig.suptitle(f"Ligand-Protein Center of Mass (COM) Analysis for {base.upper()} ({enz_name})", fontsize=18, fontweight="bold", y=0.96)
    banner_text = "Ligand-Protein COM Distance (nm) | Lower values → Closer | Values inside black boxes: Mean ± SD"

    for r in range(n_muts):
        for c in range(n_phs):
            ax_ts, ax_k = axes[r, c*2], axes[r, c*2 + 1]
            mut, ph = mut_order[r], unique_phs[c]
            
            if r == 0: 
                ax_ts.text(1.05, 1.25, f"pH {ph:.1f}", transform=ax_ts.transAxes, fontsize=16, fontweight="bold", ha="center", va="bottom")
            if c == 0: 
                ax_ts.text(-0.35, 0.5, letters[r] if r < len(letters) else "", transform=ax_ts.transAxes, fontsize=20, fontweight='bold', va='center', ha='right')

            subset = df_prot[(df_prot["mut"] == mut) & (df_prot["pH"] == ph)]
            if subset.empty:
                ax_ts.axis('off'); ax_k.axis('off'); continue
                
            df_csv = pd.read_csv(subset.iloc[0]["csv"])
            t_ns, raw_val, ma_val = df_csv["time_ns"].values, df_csv["com_nm"].values, df_csv["com_nm_ma"].values
            valid_raw = raw_val[~np.isnan(raw_val)]

            ax_ts.plot(t_ns, raw_val, color=CGREEN, alpha=0.4, linewidth=1.0, label="Raw")
            ax_ts.plot(t_ns, ma_val, color=CPURPLE, linewidth=1.5, label="Running Avg")
            
            ax_ts.set_title(f"COM of {enz_name} [{mut}]", fontsize=10, fontweight="bold")
            ax_ts.set_ylabel("COM Distance (nm)", fontweight="bold")
            ax_ts.set_xlabel("Time (ns)", fontweight="bold")
            ax_ts.set_xlim(0, 300)
            ax_ts.xaxis.set_major_locator(ticker.MultipleLocator(50))
            ax_ts.grid(True, alpha=0.3)
            
            if len(valid_raw) == 0:
                ax_ts.text(0.5, 0.5, "No Valid Data\n(Selection Empty)", transform=ax_ts.transAxes, ha="center", va="center", fontweight="bold", color="red")
                ax_k.text(0.5, 0.5, "No Valid Data", transform=ax_k.transAxes, ha="center", va="center", fontweight="bold", color="red")
                continue

            avg, std = float(np.mean(valid_raw)), float(np.std(valid_raw, ddof=1) if len(valid_raw) > 1 else 0.0)
            ax_ts.text(0.97, 0.05, f"{avg:.1f} ± {std:.1f}", transform=ax_ts.transAxes, ha="right", va="bottom", fontsize=8, fontweight="bold", zorder=10, bbox=dict(boxstyle="square,pad=0.3", fc="white", ec="black", lw=1.5, alpha=1.0))

            try:
                if len(np.unique(valid_raw)) > 1:
                    density = gaussian_kde(valid_raw)
                    xs = np.linspace(np.min(valid_raw), np.max(valid_raw), 200)
                    ax_k.plot(xs, density(xs), label="Density (KDE)", color=CGREEN, linewidth=1.5)
                else: raise ValueError
            except:
                ax_k.hist(valid_raw, density=True, alpha=0.4, bins=20, label="Density", color=CGREEN)
            
            ax_k.axvline(avg, color=CPURPLE, linestyle="--", linewidth=1.5, label="Mean")
            ax_k.set_title("COM Density Distribution", fontsize=10, fontweight="bold")
            ax_k.set_ylabel("Density", fontweight="bold")
            ax_k.set_xlabel("COM Distance (nm)", fontweight="bold")
            ax_k.grid(True, alpha=0.3)

            if r == 0 and c == 0:
                ax_ts.set_ylim(top=ax_ts.get_ylim()[1] * 1.5)
                ax_k.set_ylim(top=ax_k.get_ylim()[1] * 1.4)
                for ax_leg in [ax_ts, ax_k]:
                    leg = ax_leg.legend(fontsize=8, framealpha=1.0, loc="upper left", edgecolor="black", fancybox=False)
                    if leg: leg.get_frame().set_linewidth(1.0); leg.set_zorder(10)
    
    fig.text(0.5, 0.02, banner_text, ha="center", va="center", fontsize=10, fontweight="bold", bbox=dict(facecolor="white", edgecolor="none"))

    outprefix = os.path.join(OUTROOT, "master_grids", f"MASTER_COM_GRID_PUBLICATION_{base.upper()}")
    fig.savefig(f"{outprefix}.png", dpi=300, facecolor="white", format="png", bbox_inches="tight")
    plt.close(fig)
    print(f"[SUCCESS] Saved formatted grid -> {outprefix}.png")

def main():
    ensure_outdirs()
    systems = list_bound_systems()
    
    results = []
    with ProcessPoolExecutor(max_workers=MAX_WORKERS) as ex:
        for fut in as_completed({ex.submit(analyze_one, s): s for s in systems}):
            results.append(fut.result())

    out_df = []
    for r in results:
        if r.get("ok"):
            parts = r["rowkey"].split("_")
            base_root, mut = parts[0].lower(), parts[1] if len(parts) > 1 else "WT"
            out_df.append({"base": base_root, "mut": mut, "pH": r["pH"], "csv": r["csv"]})
            
    df = pd.DataFrame(out_df).sort_values(["base", "mut", "pH"])
    
    for base, sub_df in df.groupby("base"):
        plot_publication_grid(sub_df, base)
        
    print("\n[DONE] COM Analysis and Plotting complete.")

if __name__ == "__main__":
    main()
