"""Center-of-mass analysis for G6P-bound Hexokinase systems.

Purpose
-------
Calculates protein-pocket to G6P center-of-mass distances for bound
systems and produces publication-quality comparison grids.

Inputs
------
- Bound systems under ``$HEXOKINASE_DATA_ROOT/G6P_structure``
- Topology and trajectory files expected by the script.
- System and pH discovery is handled from the configured bound-data tree.

Outputs
-------
Under ``results/ligand_interactions/com/``:
- per-system COM analysis tables
- publication grid figures generated by the script

Run from
--------
Run from the repository root with ``HEXOKINASE_DATA_ROOT`` configured.

Usage
-----
``python scripts/ligand_interactions/com.py``

Dependencies
------------
Python, NumPy, pandas, SciPy, Matplotlib, and ``scripts.utils.paths``.
"""


